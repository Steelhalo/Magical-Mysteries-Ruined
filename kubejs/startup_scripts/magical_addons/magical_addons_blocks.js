//Blocks
StartupEvents.registry('block', event => {
  event.create('bewitchment:powered_silver_block', 'basic')
    .displayName('Powered Silver Block')
    .soundType('metal')
    .hardness(2.5)
    .resistance(3.5)
    .fullBlock(true)
    .requiresTool(true)
    .tagBlock('minecraft:mineable/pickaxe')
    .tagBlock('minecraft:needs_iron_tool')
    .texture('north', 'magical_addons:block/powered_silver_block_face')
    .texture('south', 'magical_addons:block/powered_silver_block_face')
    .texture('east', 'magical_addons:block/powered_silver_block_face_flipped_h')
    .texture('west', 'magical_addons:block/powered_silver_block_face_flipped_h')
    .texture('up', 'magical_addons:block/powered_silver_block_face_flipped_h')
    .texture('down', 'magical_addons:block/powered_silver_block_face_flipped_h')
})

